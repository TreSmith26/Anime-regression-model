"""## Genre Distribution

This section shows the most frequent genre tags among already animated manga.

Because one manga can have multiple genres, genre counts are not mutually exclusive.

These counts are descriptive references. They do not prove statistical relationships.
"""

# ============================================================
# 8. Genre Distribution — Already Animated Manga
# ============================================================

genre_cols = [col for col in final_df.columns if col.startswith("genre_")]

def top_genres_animated(df, sample_name, top_n=10):
    animated = df[df["has_anime"] == 1].copy()
    total = len(animated)

    rows = []
    for col in genre_cols:
        if col in animated.columns:
            count = int(animated[col].sum())
            rows.append({
                "Sample": sample_name,
                "Genre": col.replace("genre_", "").replace("_", " ").title(),
                "Count": count,
                "Percentage": round(count / total * 100, 2)
            })

    result = pd.DataFrame(rows)
    result = result.sort_values("Count", ascending=False).head(top_n)
    return result

