def top_genres_unanimated(df, sample_name, top_n=10):
    unanimated = df[df["has_anime"] == 0].copy()
    total = len(unanimated)

    rows = []
    for col in genre_cols:
        if col in unanimated.columns:
            count = int(unanimated[col].sum())
            rows.append({
                "Sample": sample_name,
                "Genre": col.replace("genre_", "").replace("_", " ").title(),
                "Count": count,
                "Percentage": round(count / total * 100, 2)
            })

    result = pd.DataFrame(rows)
    result = result.sort_values("Count", ascending=False).head(top_n)
    return result

